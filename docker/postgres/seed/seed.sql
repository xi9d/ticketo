BEGIN;

-- rebuild from scratch so schema changes always apply
DROP TABLE IF EXISTS order_items, orders, seats, customers, events CASCADE;

CREATE TABLE events (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text        NOT NULL,
  venue     text        NOT NULL,
  starts_at timestamptz NOT NULL
);

CREATE TABLE seats (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    bigint NOT NULL REFERENCES events(id),
  section     text   NOT NULL,
  row_label   text   NOT NULL,
  seat_number int    NOT NULL,
  price_cents int    NOT NULL CHECK (price_cents > 0),
  status      text   NOT NULL DEFAULT 'AVAILABLE'
              CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
  version     bigint NOT NULL DEFAULT 0,
  UNIQUE (event_id, section, row_label, seat_number)
);

CREATE TABLE customers (
  id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE
);

CREATE TABLE orders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint      NOT NULL REFERENCES customers(id),
  event_id    bigint      NOT NULL REFERENCES events(id),
  status      text        NOT NULL
              CHECK (status IN ('PENDING', 'PAID', 'REFUNDED', 'CANCELLED')),
  total_cents bigint      NOT NULL CHECK (total_cents >= 0),
  created_at  timestamptz NOT NULL
);

CREATE TABLE order_items (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    bigint NOT NULL REFERENCES orders(id),
  seat_id     bigint NOT NULL REFERENCES seats(id),
  price_cents int    NOT NULL CHECK (price_cents > 0)
);

CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_orders_event    ON orders(event_id);
CREATE INDEX idx_items_order     ON order_items(order_id);
CREATE INDEX idx_seats_event     ON seats(event_id);

-- events 1-50 are upcoming, 51-300 are past
INSERT INTO events (id, name, venue, starts_at)
SELECT g,
       'Event ' || g,
       'Venue ' || (1 + g % 12),
       CASE WHEN g <= 50
            THEN date_trunc('day', now()) + (g || ' days')::interval
            ELSE date_trunc('day', now()) - ((g - 50) || ' days')::interval
       END
FROM generate_series(1, 300) g;

-- 2,000 seats per event: 10 sections x 20 rows x 10 seats
-- seat ids: event 1 -> 1..2000, event 2 -> 2001..4000, ...
INSERT INTO seats (id, event_id, section, row_label, seat_number, price_cents, status)
SELECT (e.id - 1) * 2000 + n,
       e.id,
       'S' || (1 + (n - 1) / 200),
       'R' || (1 + ((n - 1) % 200) / 10),
       1 + (n - 1) % 10,
       5000 + 2500 * ((n - 1) / 1000),
       CASE WHEN e.id > 50 THEN 'SOLD' ELSE 'AVAILABLE' END
FROM events e, generate_series(1, 2000) n;

INSERT INTO customers (id, email)
SELECT g, 'user' || g || '@example.com'
FROM generate_series(1, 50000) g;

-- one historical order per past seat: 250 events x 2,000 = 500,000
-- past seats have ids 100001..600000, so order id = seat id - 100000
-- "randomness" comes from hashtext(), so every run is identical
INSERT INTO orders (id, customer_id, event_id, status, total_cents, created_at)
SELECT s.id - 100000,
       1 + (hashtext(s.id::text) & 2147483647) % 50000,
       s.event_id,
       CASE WHEN (hashtext(s.id::text || 's') & 2147483647) % 20 = 0
            THEN 'REFUNDED' ELSE 'PAID' END,
       s.price_cents,
       e.starts_at - (((hashtext(s.id::text || 't') & 2147483647) % 60) + 1) * interval '1 day'
FROM seats s
JOIN events e ON e.id = s.event_id
WHERE s.event_id > 50;

INSERT INTO order_items (order_id, seat_id, price_cents)
SELECT o.id, o.id + 100000, o.total_cents
FROM orders o;

-- move identity sequences past the seeded ids so the app can insert new rows
SELECT setval(pg_get_serial_sequence('events',      'id'), (SELECT max(id) FROM events));
SELECT setval(pg_get_serial_sequence('seats',       'id'), (SELECT max(id) FROM seats));
SELECT setval(pg_get_serial_sequence('customers',   'id'), (SELECT max(id) FROM customers));
SELECT setval(pg_get_serial_sequence('orders',      'id'), (SELECT max(id) FROM orders));
SELECT setval(pg_get_serial_sequence('order_items', 'id'), (SELECT max(id) FROM order_items));

ANALYZE;
COMMIT;